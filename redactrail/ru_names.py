def _patronymic_pair(name: str) -> tuple[str, str]:
    """Образовать отчество из имени.

    Правила по окончанию имени:
    «-ий» → «-ьевич»/«-ьевна» (Дмитрий → Дмитриевич, Арсений → Арсеньевич),
    «-й»  → «-евич»/«-евна» (Андрей → Андреевич),
    «-ь»  → «-евич»/«-евна» (Игорь → Игоревич),
    «-а/-я» → «-ич»/«-ична» (Никита → Никитич),
    иначе → «-ович»/«-овна» (Иван → Иванович).
    """
    if name in _IRREGULAR_PATRONYMICS:
        return _IRREGULAR_PATRONYMICS[name]
    stem = name.replace("ё", "е")
    if stem.endswith("ий"):
        base = stem[:-2]
        return base + "ьевич", base + "ьевна"
    if stem.endswith("й"):
        base = stem[:-1]
        return base + "евич", base + "евна"
    if stem.endswith("ь"):
        base = stem[:-1]
        return base + "евич", base + "евна"
    if stem.endswith(("а", "я")):
        base = stem[:-1]
        return base + "ич", base + "ична"
    return stem + "ович", stem + "овна"


def _build_patronymics() -> tuple[frozenset[str], frozenset[str]]:
    male: set[str] = set()
    female: set[str] = set()
    for name in MALE_NAMES:
        masc, fem = _patronymic_pair(name)
        male.add(masc)
        female.add(fem)
    for name, (masc, fem) in _IRREGULAR_PATRONYMICS.items():
        male.add(masc)
        female.add(fem)
    return frozenset(male), frozenset(female)


